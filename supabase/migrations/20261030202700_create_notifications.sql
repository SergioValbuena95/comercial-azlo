create table public.notifications (
    id bigint generated by default as identity primary key,

    project_id bigint not null,

    user_id bigint,

    created_by bigint,

    title text not null,

    message text not null,

    old_state text,

    new_state text,

    is_read boolean not null default false,

    created_at timestamptz not null default now(),

    constraint notifications_project_id_fkey
        foreign key (project_id)
        references public.projects(id)
        on delete cascade,

    constraint notifications_user_id_fkey
        foreign key (user_id)
        references public.users(id)
        on delete cascade,

    constraint notifications_created_by_fkey
        foreign key (created_by)
        references public.users(id)
        on delete set null
);

create index notifications_user_id_idx
    on public.notifications(user_id);

create index notifications_project_id_idx
    on public.notifications(project_id);

create index notifications_is_read_idx
    on public.notifications(is_read);

create index notifications_created_at_idx
    on public.notifications(created_at desc);

alter table public.notifications enable row level security;

create policy "Authenticated users can read notifications"
    on public.notifications
    for select
    to authenticated
    using (true);

create policy "Authenticated users can insert notifications"
    on public.notifications
    for insert
    to authenticated
    with check (true);

create policy "Authenticated users can update notifications"
    on public.notifications
    for update
    to authenticated
    using (true)
    with check (true);

create policy "Authenticated users can delete notifications"
    on public.notifications
    for delete
    to authenticated
    using (true);

alter publication supabase_realtime add table public.notifications;

